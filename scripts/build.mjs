// Builds dist/: the static app that Vercel serves (index.html, hashed JS/CSS,
// service worker, icons, manifest). The Family-mode API is the Vercel Function in
// api/index.js, which Vercel builds from source; nothing here bundles server code.
import {build, transform} from "esbuild";
import {createHash} from "node:crypto";
import {existsSync} from "node:fs";
import {mkdir, readFile, readdir, rm, writeFile} from "node:fs/promises";
import {dirname, join} from "node:path";
import {fileURLToPath} from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dist = join(root, "dist");
const src = p => join(root, "src", p);

const appBundle = await build({entryPoints: [src("client/app.js")], bundle: true, loader: {".webp": "dataurl"}, format: "esm", minify: true, write: false, target: ["es2020", "safari14"], legalComments: "none"});
const appJs = appBundle.outputFiles[0].text;
const audioBundle = await build({entryPoints: [src("client/audio-entry.js")], bundle: true, format: "esm", minify: true, write: false, target: ["es2020", "safari14"], legalComments: "none"});
const audioJs = audioBundle.outputFiles[0].text;
// The felt UI pieces (src/client/felt, made by scripts/build-felt-assets.py) and the rounded font.
// skins.json says which components wear which felt piece; the CSS for that is generated here so the
// slice insets always match the processed images.
const feltSlices = JSON.parse(await readFile(src("client/felt/felt-slices.json"), "utf8"));
const feltSkins = JSON.parse(await readFile(src("client/felt/skins.json"), "utf8"));
const round4 = n => Math.round(n * 10000) / 10000;
const feltCss = ["/* Generated by scripts/build.mjs from src/client/felt/skins.json. */"];
for (const {asset, selectors, fill = true, repeat = "round stretch", center} of feltSkins.skins) {
  const m = feltSlices[asset];
  if (!m) throw new Error(`felt skin "${asset}" has no processed image`);
  const [t, r, b, l] = m.slice;
  const [bl, bt, br, bb] = m.body; // body insets are [left, top, right, bottom]
  feltCss.push(`${selectors.join(",")}{--skin-img:url("/felt/${asset}.webp");--skin-slice:${t} ${r} ${b} ${l}${fill ? " fill" : ""};--skin-wt:${round4(t / m.h)};--skin-wr:${round4(r / m.h)};--skin-wb:${round4(b / m.h)};--skin-wl:${round4(l / m.h)};--skin-bt:${round4(bt / m.h)};--skin-bb:${round4(bb / m.h)};--skin-bl:${round4(bl / m.h)};--skin-br:${round4(br / m.h)};--skin-repeat:${repeat};--skin-center:${center || m.center}}`);
}
// Every skinned component: the felt piece replaces its border, background and shadow; text stays live.
const W = side => `calc(var(--felt-h, 48px) * var(--skin-w${side}))`;
const allSkinned = [...new Set(feltSkins.skins.flatMap(skin => skin.selectors))];
// The piece's own felt colour underneath it, inset to half of each edge (so it never shows outside
// the rounded shape): fills the middle of pieces drawn without one (the bubble) and hides the
// hairline gaps browsers can leave between the stretched sections of the others.
// Three bands of the piece's colour: the middle, the straight run between the rounded ends (full
// felt height) and the full-width band between the top and bottom edges. Each sits only where the
// felt is solid, so none ever shows outside the shape.
const fh = "var(--felt-h, 48px)";
const ins = v => `calc(${fh} * var(--skin-${v}) + 1px)`;
const cut = v => `calc(${fh} * var(--skin-w${v}) - 2px)`;
const half = side => `calc(${fh} * var(--skin-w${side}) / 2)`;
const fill = "linear-gradient(var(--skin-center),var(--skin-center))";
const underlay = [
  `background:${fill},${fill},${fill}!important`,
  "background-repeat:no-repeat!important;background-origin:border-box!important;background-clip:border-box!important",
  `background-position:${half("l")} ${half("t")},${cut("l")} ${ins("bt")},${ins("bl")} ${cut("t")}!important`,
  `background-size:calc(100% - ${half("l")} - ${half("r")}) calc(100% - ${half("t")} - ${half("b")}),calc(100% - ${cut("l")} - ${cut("r")}) calc(100% - ${ins("bt")} - ${ins("bb")}),calc(100% - ${ins("bl")} - ${ins("br")}) calc(100% - ${cut("t")} - ${cut("b")})!important`
].join(";");
feltCss.splice(1, 0, `${allSkinned.join(",")}{border:0 solid transparent!important;border-image-source:var(--skin-img)!important;border-image-slice:var(--skin-slice)!important;border-image-width:${W("t")} ${W("r")} ${W("b")} ${W("l")}!important;border-image-outset:0!important;border-image-repeat:var(--skin-repeat)!important;box-shadow:none!important;${underlay}}`);
// Text sits in the optical centre of each piece: the vertical padding is worked out from the
// piece's own shape (its top edge and the shadow under it) and the text's line height, so a
// single line is exactly centred on the felt and longer text grows evenly.
const padded = [...new Set(feltSkins.skins.filter(skin => skin.fill !== false).flatMap(skin => skin.selectors))];
const inner = "(var(--felt-h, 48px) * (1 - var(--skin-bt) - var(--skin-bb)) - 1lh) / 2";
feltCss.push(`${padded.join(",")}{min-height:var(--felt-h, 48px);padding-top:calc(${inner} + var(--felt-h, 48px) * var(--skin-bt))!important;padding-bottom:calc(${inner} + var(--felt-h, 48px) * var(--skin-bb))!important}`);
// Every processed felt image ships: the stretchable pieces plus the round badges (felt/badge-*.webp).
const FELT = [...new Set([...Object.keys(feltSlices).map(name => `/felt/${name}.webp`), ...(await readdir(src("client/felt"))).filter(name => name.endsWith(".webp")).map(name => `/felt/${name}`)])];
const felt = Object.fromEntries(await Promise.all(FELT.map(async path => [path, await readFile(src(`client${path}`))])));
const FONT_WEIGHTS = [700, 800, 900];
const fonts = Object.fromEntries(await Promise.all(FONT_WEIGHTS.map(async w => [`/fonts/nunito-${w}.woff2`, await readFile(join(root, "node_modules", "@fontsource", "nunito", "files", `nunito-latin-${w}-normal.woff2`))])));
const fontCss = FONT_WEIGHTS.map(w => `@font-face{font-family:"Nunito";font-style:normal;font-weight:${w};font-display:swap;src:url("/fonts/nunito-${w}.woff2") format("woff2")}`).join("\n");
const feltDesign = [fontCss, await readFile(src("client/design.css"), "utf8"), feltCss.join("\n")].join("\n");

// One design system for every page: shared tokens/components (design.css + felt skins) first, then the app layer.
const css = [feltDesign, await readFile(src("client/styles.css"), "utf8")].join("\n");
const logo = await readFile(src("client/logo.webp"));
const cloudSync = await readFile(src("client/cloud-sync.js"), "utf8");
const account = await readFile(src("client/account.js"), "utf8");
const ICONS = ["favicon.ico", "favicon-32.png", "apple-touch-icon.png", "icon-192.png", "icon-512.png"];
const icons = Object.fromEntries(await Promise.all(ICONS.map(async name => [`/${name}`, await readFile(src(`client/icons/${name}`))])));
const manifest = await readFile(src("client/manifest.webmanifest"), "utf8");
const momLaunch = await readFile(src("client/mom-mode/entry-fix.js"), "utf8");

const runtimeKnowledgePath = src("client/mom-mode/knowledge.runtime.json");
const hasMomRuntime = existsSync(runtimeKnowledgePath);
const LEGACY_MOM_JS = ["knowledge.js", "knowledge.general.js", "knowledge.generated.js", "facets.js", "engine.js", "deduction.js", "copy.js", "adapter.js", "app.js", "debug.js"];
const RUNTIME_MOM_JS = ["copy.js", "app.js", "debug.js"];
const MOM_JS = hasMomRuntime ? RUNTIME_MOM_JS : LEGACY_MOM_JS;
const MOM_CSS = ["styles.css", "character.css"];
const MOM_STATIC = ["pam.webp", "pam-v2.webp"];
const legacyMomScriptChain = '<script src="./knowledge.js" defer></script><script src="./knowledge.general.js" defer></script><script src="./knowledge.generated.js" defer></script><script src="./facets.js" defer></script><script src="./engine.js" defer></script><script src="./deduction.js" defer></script><script src="./copy.js" defer></script><script src="./adapter.js" defer></script><script src="./app.js" defer></script><script src="./debug.js" defer></script>';
const runtimeMomScriptChain = '<script src="./knowledge.runtime.js" defer></script><script src="./runtime-entry.js" defer></script><script src="./copy.js" defer></script><script src="./app.js" defer></script><script src="./debug.js" defer></script>';
let momIndex = await readFile(src("client/mom-mode/index.html"), "utf8");
if (hasMomRuntime) {
  if (!momIndex.includes(legacyMomScriptChain)) throw new Error("Mom index script chain changed; compact runtime build cannot safely replace it");
  momIndex = momIndex.replace(legacyMomScriptChain, runtimeMomScriptChain);
}
const momJsSource = Object.fromEntries(await Promise.all(MOM_JS.map(async name => [name, await readFile(src(`client/mom-mode/${name}`), "utf8")])));
const momCssSource = {
  // The shared design system (src/client/design.css), so Pam's page belongs to the same game world.
  "design.css": feltDesign,
  ...Object.fromEntries(await Promise.all(MOM_CSS.map(async name => [name, await readFile(src(`client/mom-mode/${name}`), "utf8")])))
};
const momStatic = Object.fromEntries(await Promise.all(MOM_STATIC.map(async name => [name, await readFile(src(`client/mom-mode/${name}`))])));

const hash = value => createHash("sha256").update(value).digest("hex").slice(0, 10);
const appName = `/assets/app.${hash(appJs)}.js`;
const audioName = `/assets/audio-settings.${hash(audioJs)}.js`;
const cssName = `/assets/styles.${hash(css)}.css`;

const momJs = {};
for (const [name, source] of Object.entries(momJsSource)) {
  momJs[name] = (await transform(source, {loader: "js", minify: true, target: ["es2020", "safari14"], legalComments: "none"})).code;
}
if (hasMomRuntime) {
  const runtimeData = JSON.parse(await readFile(runtimeKnowledgePath, "utf8"));
  if (!runtimeData?.meta?.conceptCount || runtimeData.meta.conceptCount < 50000) throw new Error(`Compact Mom runtime is incomplete: ${runtimeData?.meta?.conceptCount ?? 0} concepts`);
  momJs["knowledge.runtime.js"] = `window.MOM_RUNTIME_KNOWLEDGE=${JSON.stringify(runtimeData)};`;
  const runtimeBundle = await build({entryPoints: [src("client/mom-mode/runtime-entry.js")], bundle: true, format: "iife", minify: true, write: false, target: ["es2020", "safari14"], legalComments: "none"});
  momJs["runtime-entry.js"] = runtimeBundle.outputFiles[0].text;
}
const momCss = {};
for (const [name, source] of Object.entries(momCssSource)) {
  momCss[name] = (await transform(source, {loader: "css", minify: true, target: ["es2020", "safari14"], legalComments: "none"})).code;
}
const momAssetPath = (name, body) => `./assets/${name.replace(/\.(js|css)$/, "")}.${hash(body)}.${name.endsWith(".js") ? "js" : "css"}`;
const momAssetFiles = {};
const momAssetUrls = [];
let momPage = momIndex;
for (const [name, body] of Object.entries({...momCss, ...momJs})) {
  const relative = momAssetPath(name, body);
  momPage = momPage.replaceAll(`./${name}`, relative);
  const canonical = `/mom/${relative.replace(/^\.\//, "")}`;
  const legacy = `/mom-mode/${relative.replace(/^\.\//, "")}`;
  momAssetFiles[canonical] = body;
  momAssetFiles[legacy] = body;
  momAssetUrls.push(canonical);
}

const html = (await readFile(src("client/index.html"), "utf8")).replace("%APP_JS%", appName).replace("%AUDIO_JS%", audioName).replace("%STYLES_CSS%", cssName);
const swTemplate = await readFile(src("client/sw.js"), "utf8");
const iconHash = createHash("sha256");
for (const body of [...Object.values(icons), ...Object.values(felt), ...Object.values(fonts)]) iconHash.update(body);
const momHash = createHash("sha256");
momHash.update(momPage);
for (const body of Object.values(momJs)) momHash.update(body);
for (const body of Object.values(momCss)) momHash.update(body);
for (const body of Object.values(momStatic)) momHash.update(body);
const version = hash(appJs + audioJs + css + html + momLaunch + cloudSync + account + logo + iconHash.digest("hex") + momHash.digest("hex") + manifest + swTemplate);
const page = html.replace("%APP_VERSION%", version);
const momPrecache = ["/mom/", ...momAssetUrls, "/mom/pam.webp", "/mom/pam-v2.webp"];
const swSource = swTemplate
  .replace("%VERSION%", version)
  .replace("%PRECACHE%", JSON.stringify(["/", appName, audioName, cssName, "/logo.webp", "/mom-launch.js", "/cloud-sync.js", "/account.js", "/favicon.ico", "/favicon-32.png", "/manifest.webmanifest", ...FELT, ...Object.keys(fonts), ...momPrecache]));
if (swSource.includes("%")) throw new Error("sw.js still has an unfilled %PLACEHOLDER%");
const sw = (await build({stdin: {contents: swSource, loader: "js"}, minify: true, write: false, format: "iife"})).outputFiles[0].text;

const files = {
  "/index.html": page,
  [appName]: appJs,
  [audioName]: audioJs,
  [cssName]: css,
  "/logo.webp": logo,
  "/mom-launch.js": momLaunch,
  "/cloud-sync.js": cloudSync,
  "/account.js": account,
  "/sw.js": sw,
  ...icons,
  ...felt,
  ...fonts,
  "/manifest.webmanifest": manifest,
  "/mom/index.html": momPage,
  "/mom-mode/index.html": momPage,
  ...momAssetFiles
};
for (const [name, body] of Object.entries(momStatic)) {
  files[`/mom/${name}`] = body;
  files[`/mom-mode/${name}`] = body;
}

await rm(dist, {recursive: true, force: true});
for (const [path, body] of Object.entries(files)) {
  const out = join(dist, path);
  await mkdir(dirname(out), {recursive: true});
  await writeFile(out, body);
}
console.log(`Built version ${version}: ${Object.keys(files).length} static files in dist/ (${hasMomRuntime ? "compact Mom runtime" : "legacy Mom runtime"})`);
