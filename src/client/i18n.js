/** Put a narrow no-break space before French high punctuation (and keep it from wrapping). */
export function frenchTypography(text) {
  return text.replace(/[  ]+([!?;:»])/g, " $1").replace(/(«)[  ]+/g, "$1 ");
}

export const STRINGS = {
  en: EN,
  fr: Object.fromEntries(Object.entries(FR).map(([key, value]) => [key, frenchTypography(value)]))
};

/** Name of a game language ("en" | "fr"), written in the interface language. */
export function languageName(t, code) {
  return t(code === "fr" ? "langFrench" : "langEnglish");
}

export function translator(getLang) {
  return (key, vars = {}) => {
    const lang = getLang();
    const template = STRINGS[lang]?.[key] ?? STRINGS.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? ""));
  };
}
